#!/usr/bin/env python3
"""
pcl_symbol_sets.py -- HP PCL5 symbol-set byte->Unicode tables (stdlib only).

WHY THIS EXISTS (planning #260)
--------------------------------
tools/pcl_text.py and tools/pcl_render.py both decoded EVERY text byte in a
captured PCL stream via a single fixed cp437 table, discarding the symbol-set
selection escape `ESC(<id><letter>` (e.g. `ESC(10U`, `ESC(7J`) entirely --
recognized and skipped, never interpreted. That is correct ONLY while the
active set is "10U" (PC-8, i.e. code page 437 -- WordStar's default body
text). WordStar 7's LJ6DTP-patched LaserJet driver, and the PostScript-font
sampler documents (`sawyer/PRINTERS/PS/PSSAMPLE.WS`, `FONTCRIB.PS`,
`fixtures-ws5/PS.TST`), deliberately switch the ACTIVE symbol set mid-line to
reach glyphs PC-8 has no slot for: curly quotes, the copyright/registered/
trademark signs, and (for the PostScript docs) the full Greek alphabet and
math operator repertoire of the Symbol font. Decoding those runs through
cp437 anyway silently prints the WRONG character.

Verified directly against `ws7-prints/v1/LJ6DTP.pcl` (planning #260 evidence,
Jon's own paper scan of the real WS7 LaserJet printout): the heading
"<0xB0>Color<0xB1>" is bracketed `ESC(7J<B0>` / `ESC(7J<B1>` and the paper
prints curly double quotes ("Color"); the title-bar copyright line carries
`ESC(5M<E3>` (Univers/sans context) and, elsewhere in the same document,
`ESC(5M<D3>` (CG Times/serif context), both printing "(c)"; and the
apostrophe in "WordStar's" is bracketed `ESC(7J<27>` between two `ESC(10U`
runs, printing as a curly apostrophe -- NOT, as first hypothesized, a bare
0x27 under plain PC-8 (PC-8's own 0x27 stays straight; the driver switches
symbol set for that one byte, same mechanism as the Color quotes).

SOURCES
-------
- 10U (PC-8, code page 437): no table below -- callers fall back to Python's
  own `bytes.decode('cp437')`, which the existing corpus baseline (394
  files) already validates. Cross-checked against the RedTitan pcl_10u.pdf
  table (see below): identical over 0x20-0xFF except four codepoints where
  the two published PC-8 conventions diverge by canonical-equivalent-but-
  distinct Unicode code points (0x7F DEL glyph, and three Greek-letter vs.
  math-operator lookalikes at 0xE4/0xEA/0xFA) -- cp437 is kept as-is since
  it is what the shipped corpus was validated against, not a guess.
- 7J (DeskTop), 5M (PS Math), 19M (Symbol), 8U (Roman-8): transcribed from
  RedTitan Technology's "PCL Symbol Set: <id> Unicode glyph correspondence
  tables" (pclviewer.com/resources/symbolset/pcl_<id>.pdf, (c) RedTitan
  Technology 2005; fetched 2026-09-10, `pdftotext -layout` + a `$XX UXXXX`
  regex extraction, spot-verified against src/ctrlkd/symbolmap.py's
  independently-sourced Adobe Symbol encoding for the whole 19M table --
  e.g. 'A' at $41 -> U+0391 GREEK CAPITAL ALPHA, '"' at $22 -> U+2200 FOR
  ALL -- exact agreement across every symbol shared between the two
  sources). Byte ranges these tables never assign (HP never registered a
  glyph there) are simply absent from the dict below; `decode_byte` falls
  back to cp437 for any byte a table doesn't cover.
- 5M's 0xE3 CORRECTION: RedTitan's own probe left 5M's 0xE2-0xE4 blank
  ("-- --"), but this project's real capture uses `ESC(5M<E3>` for the
  sans-serif (c) and `ESC(5M<D3>` for the serif one (matching the LJ6DTP
  deep-read's own finding, 2026-08-05: "the sans-serif (c) (PS Math E3)
  goes to Arial/Omega/Univers while the serif (c) (PS Math D3) goes to
  Times/Times New Roman"). 19M -- built from the SAME underlying HP Symbol
  font repertoire as 5M and RedTitan's own probe for IT succeeded over
  0xE2-0xE4 -- mirrors 0xD2-0xD4 (Registered/Copyright/Trademark) exactly
  at 0xE2-0xE4, corroborating that 5M's real table does too. Only 0xE3 is
  added here (the one actually observed in this corpus); 0xE2/0xE4 are left
  out since nothing in this corpus exercises them and adding them
  unobserved would be a guess, not a verified fact -- pass-through (cp437
  fallback) beats a wrong guess (src/ctrlkd/symbolmap.py's own stated
  principle).

NOT COVERED (documented gap, not silently wrong): symbol sets "15U" and "4U"
also appear in this corpus (LJ6DTP.pcl only, 8 and 2 occurrences) and "579L"
(Wingdings, 10 PostScript-family files, 1013 occurrences) -- none are in
this table. 15U prints single-byte samples of LJ6DTP's Pi-font rounded box
corners inside the document's own substitution chart (not standard HP
catalog IDs; no public table found); 4U's observed bytes (0x27, 0x60) are
in the pure-ASCII range where 4U agrees with cp437 anyway, so the fallback
is not merely a stopgap there, it is already correct. 579L/Wingdings is a
pre-existing, already-documented gap (pcl_render.py's own TYPEFACE_FAMILY
comment: "this project has no metrically-honest Wingdings table") -- left
alone here, not newly introduced.
"""

