# HP's own symbol-set naming, keyed by the id+letter WordStar emits in
# `ESC(<id><letter>` (e.g. "10U", "7J"). Names per rexswain.com/hpsymset.html
# (fetched 2026-09-10), cross-checked against the RedTitan PDF titles above.
SYMBOL_SET_NAMES = {
    "10U": "PC-8 (Code Page 437)",
    "8U": "Roman-8",
    "7J": "DeskTop",
    "5M": "PS Math",
    "19M": "Symbol",
}

SYMBOL_SET_TABLES = {
    "7J": TABLE_7J,
    "5M": TABLE_5M,
    "19M": TABLE_19M,
    "8U": TABLE_8U,
    # "10U" deliberately absent: callers fall back to cp437 for it, and for
    # every OTHER/unimplemented set (15U, 4U, 579L, no set seen yet) -- see
    # module docstring's "NOT COVERED" section.
}


def decode_byte(b, symbol_set):
    """One byte -> one Unicode character, under the symbol set active when
    it was printed (a `ESC(<id><letter>` id string, or None before any has
    been seen). Falls back to cp437 for 10U, any table this module does not
    carry, or any byte a covered table itself doesn't assign -- matching
    this project's existing "pass-through beats a wrong guess" rule."""
    table = SYMBOL_SET_TABLES.get(symbol_set)
    if table is not None:
        cp = table.get(b)
        if cp is not None:
            return chr(cp)
    return bytes((b,)).decode("cp437", "replace")


def decode_run(data, symbol_set):
    """A whole run's bytes -> str, one call to decode_byte per byte (a run
    never changes symbol set mid-run in this corpus -- the driver always
    closes and reopens a text run at a symbol-set switch, confirmed by the
    "WordStar's" apostrophe case in the module docstring)."""
    return "".join(decode_byte(b, symbol_set) for b in data)
